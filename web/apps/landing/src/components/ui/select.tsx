// outline: the shadcn field look. ghost: no border or fill until hovered, for quiet places like the
// footer.
const triggerVariants = {
  outline: "border-input bg-transparent dark:bg-input/30 dark:hover:bg-input/50",
  ghost: "border-transparent bg-transparent hover:bg-foreground/5 data-popup-open:bg-foreground/5 dark:hover:bg-white/10 dark:data-popup-open:bg-white/10",
}

function SelectTrigger({
  className,
  size = "default",
  variant = "outline",
  chevron = true,
  children,
  ...props
}: SelectPrimitive.Trigger.Props & {
  size?: "sm" | "default"
  variant?: keyof typeof triggerVariants
  chevron?: boolean
}) {
  return (
    <SelectPrimitive.Trigger
      data-slot="select-trigger"
      data-size={size}
      className={cn(
        "flex w-fit items-center justify-between gap-1.5 rounded-lg border py-2 pr-2 pl-2.5 text-sm whitespace-nowrap transition-colors outline-none select-none focus-visible:border-ring focus-visible:ring-3 focus-visible:ring-ring/50 disabled:cursor-not-allowed disabled:opacity-50 aria-invalid:border-destructive aria-invalid:ring-3 aria-invalid:ring-destructive/20 data-placeholder:text-muted-foreground data-[size=default]:h-8 data-[size=sm]:h-7 data-[size=sm]:rounded-[min(var(--radius-md),10px)] *:data-[slot=select-value]:line-clamp-1 *:data-[slot=select-value]:flex *:data-[slot=select-value]:items-center *:data-[slot=select-value]:gap-1.5 dark:aria-invalid:border-destructive/50 dark:aria-invalid:ring-destructive/40 [&_svg]:pointer-events-none [&_svg]:shrink-0 [&_svg:not([class*='size-'])]:size-4",
        triggerVariants[variant],
        className
      )}
      {...props}
    >
      {children}
      {chevron ? (
        <SelectPrimitive.Icon
          render={
            <ChevronDownIcon className="pointer-events-none size-4 text-muted-foreground" />
          }
        />
      ) : null}
    </SelectPrimitive.Trigger>
  )
}

function SelectContent({
  className,
  children,
  side = "bottom",
  sideOffset = 4,
  align = "center",
  alignOffset = 0,
  alignItemWithTrigger = true,
  ...props
}: SelectPrimitive.Popup.Props &
  Pick<
    SelectPrimitive.Positioner.Props,
    "align" | "alignOffset" | "side" | "sideOffset" | "alignItemWithTrigger"
  >) {
  return (
    <SelectPrimitive.Portal>
      <SelectPrimitive.Positioner
        side={side}
        sideOffset={sideOffset}
        align={align}
        alignOffset={alignOffset}
        alignItemWithTrigger={alignItemWithTrigger}
        className="isolate z-50"
      >
        <SelectPrimitive.Popup
          data-slot="select-content"
          data-align-trigger={alignItemWithTrigger}
          className={cn("relative isolate z-50 max-h-(--available-height) w-(--anchor-width) min-w-36 origin-(--transform-origin) overflow-x-hidden overflow-y-auto rounded-xl bg-popover/70 text-popover-foreground shadow-lg ring-1 ring-foreground/[0.04] backdrop-blur-xl backdrop-saturate-150 [@media(prefers-reduced-transparency:reduce)]:bg-popover [@media(prefers-reduced-transparency:reduce)]:backdrop-blur-none", className )}
          // enMirror: Motion animates the popup, from its trigger (origin-(--transform-origin)),
          // 150 ms strong ease-out. Opacity and transform run as WAAPI animations, which Base UI
          // waits for before unmounting a closing popup. Aligned over the trigger: no motion.
          render={(popupProps, state) =>
            alignItemWithTrigger ? (
              <div {...popupProps} />
            ) : (
              <m.div
                {...(popupProps as HTMLMotionProps<"div">)}
                style={popupProps.style as MotionStyle}
                initial={{ opacity: 0, transform: "scale(0.96)" }}
                animate={state.open ? { opacity: 1, transform: "scale(1)" } : { opacity: 0, transform: "scale(0.96)" }}
                transition={{ duration: 0.15, ease: easeOut }}
              />
            )
          }
          {...props}
        >
          <SelectScrollUpButton />
          <SelectPrimitive.List>{children}</SelectPrimitive.List>
          <SelectScrollDownButton />
        </SelectPrimitive.Popup>
      </SelectPrimitive.Positioner>
    </SelectPrimitive.Portal>
  )
}

